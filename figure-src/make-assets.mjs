// Turns the generated figure layers and fig.json into the site's assets:
//   ../assets/figure-back.svg, ../assets/figure-mount.svg, ../assets/figure-front.svg, ../assets/beacon-light.svg
//   ../js/figure-data.js                                   (anchors for the particle layers)
// Usage (from this folder):  node build.mjs && node make-assets.mjs [siteRoot]
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = process.argv[2] || join(HERE, "..");
const meta = JSON.parse(readFileSync(join(HERE, "fig.json"), "utf8"));
const css = [
  readFileSync(join(HERE, "kit/iso.css"), "utf8").trim(),
  readFileSync(join(HERE, "palette.css"), "utf8").trim(),
].join("\n");

const body = (file) => readFileSync(join(HERE, file), "utf8").replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const wrap = (inner) => `<svg xmlns="http://www.w3.org/2000/svg" class="iso-svg iso fig" width="${meta.W}" height="${meta.H}" viewBox="0 0 ${meta.W} ${meta.H}" aria-hidden="true"><style>${css}</style>${inner}</svg>\n`;

mkdirSync(join(SITE, "assets"), { recursive: true });
mkdirSync(join(SITE, "js"), { recursive: true });
writeFileSync(join(SITE, "assets/figure-back.svg"), wrap(body("fig-back.svg")));
writeFileSync(join(SITE, "assets/figure-mount.svg"), wrap(body("fig-mount.svg")));
copyFileSync(join(HERE, "fig-beacon-light.svg"), join(SITE, "assets/beacon-light.svg"));
// the printed name lives in index.html (so it is editable text in the page font), not in the SVG
writeFileSync(join(SITE, "assets/figure-front.svg"), wrap(body("fig-front.svg").replace(/<text[\s\S]*?<\/text>/g, "")));

const g = meta.fx.ground;
const rect = [Math.round(g[0] - 540), Math.round(g[1] - 450), 1000, 600];
writeFileSync(join(SITE, "js/figure-data.js"), `// Generated by figure-src/make-assets.mjs — do not edit by hand.
// Figure size in SVG units, and where the engines, ground, trench and mount are (for js/fx.js).
window.FIGURE = ${JSON.stringify({ W: meta.W, H: meta.H, name: meta.name, fx: { ...meta.fx, rect } })};
`);
console.log("assets written to", SITE, "· figure", meta.W, "x", meta.H, "· particle rect", rect.join(","));
